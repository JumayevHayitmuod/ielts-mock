class Command(BaseCommand):
    help = "Create or refresh a set of 100 IELTS vocabulary words."

    def handle(self, *args, **options):
        missing_translations = {word for word, _, _ in WORDS} - TRANSLATIONS_UZ.keys()
        if missing_translations:
            self.stderr.write(f"Missing Uzbek translations: {', '.join(sorted(missing_translations))}")
            return
        definitions = [definition for _, _, definition in WORDS]
        for index, (word, part_of_speech, definition) in enumerate(WORDS):
            wrong_options = [definitions[(index + offset) % len(definitions)] for offset in range(1, 4)]
            Word.objects.update_or_create(
                word=word,
                defaults={
                    "part_of_speech": part_of_speech,
                    "definition": definition,
                    "translation_uz": TRANSLATIONS_UZ[word],
                    "band_level": 6 + index % 3,
                    "wrong_options": wrong_options,
                },
            )
        Word.objects.filter(word="book").update(translation_uz="kitob")
        self.stdout.write(self.style.SUCCESS(f"{len(WORDS)} vocabulary words ready."))
