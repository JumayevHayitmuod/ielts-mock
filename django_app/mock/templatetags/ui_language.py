@register.simple_tag
def ui(text):
    if (get_language() or "uz").startswith("uz"):
        return UZ.get(text, text)
    return text


@register.filter
def translate_ui(text):
    if (get_language() or "uz").startswith("uz"):
        return UZ.get(str(text), str(text))
    return text
